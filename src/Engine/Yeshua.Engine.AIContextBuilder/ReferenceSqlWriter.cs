    private const string FieldQuerySql = """
-- Adjust only these values.
DECLARE @ApplicationName NVARCHAR(300) = __APPLICATION__;
DECLARE @Version NVARCHAR(200) = __VERSION__;
DECLARE @FieldQualifiedName NVARCHAR(2000) = __SYMBOL__;
DECLARE @IncludeSameName BIT = 1;

DECLARE @BuildId UNIQUEIDENTIFIER;
SELECT TOP (1) @BuildId = b.BuildId
FROM OI_Builds b
JOIN OI_Applications a ON a.ApplicationId = b.ApplicationId
WHERE a.Name = @ApplicationName AND b.Version = @Version
ORDER BY b.GeneratedAtUtc DESC;

IF @BuildId IS NULL THROW 51000, 'Build not found.', 1;

DECLARE @FieldName NVARCHAR(500) = RIGHT(@FieldQualifiedName, CHARINDEX('.', REVERSE(@FieldQualifiedName) + '.') - 1);
CREATE TABLE #TargetFields (SymbolId UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, MatchKind NVARCHAR(30) NOT NULL);

INSERT INTO #TargetFields
SELECT SymbolId, N'EXACT_SYMBOL'
FROM OI_Symbols
WHERE BuildId = @BuildId
  AND Kind IN (N'FIELD', N'PROPERTY')
  AND QualifiedName = @FieldQualifiedName;

IF @IncludeSameName = 1
BEGIN
    INSERT INTO #TargetFields
    SELECT s.SymbolId, N'SAME_NAME_CANDIDATE'
    FROM OI_Symbols s
    WHERE s.BuildId = @BuildId
      AND s.Kind IN (N'FIELD', N'PROPERTY')
      AND s.Name = @FieldName
      AND NOT EXISTS (SELECT 1 FROM #TargetFields t WHERE t.SymbolId = s.SymbolId);
END;

SELECT t.MatchKind, s.Kind, s.QualifiedName, f.RelativePath, d.StartLine, d.EndLine
FROM #TargetFields t
JOIN OI_Symbols s ON s.SymbolId = t.SymbolId
LEFT JOIN OI_Declarations d ON d.BuildId = @BuildId AND d.SymbolId = s.SymbolId
LEFT JOIN OI_Files f ON f.FileId = d.FileId
ORDER BY t.MatchKind, s.QualifiedName, f.RelativePath, d.StartLine;

SELECT t.MatchKind, s.QualifiedName AS FieldName, r.AccessKind, f.RelativePath, r.Line, r.ColumnNumber,
       owner.QualifiedName AS ContainingFunction
FROM #TargetFields t
JOIN OI_Symbols s ON s.SymbolId = t.SymbolId
JOIN OI_FieldReferences r ON r.BuildId = @BuildId AND r.FieldSymbolId = t.SymbolId
JOIN OI_Files f ON f.FileId = r.FileId
LEFT JOIN OI_Symbols owner ON owner.SymbolId = r.ContainingFunctionId
ORDER BY t.MatchKind, s.QualifiedName, r.AccessKind, f.RelativePath, r.Line;

SELECT tr.Token, tr.ReferenceKind, f.RelativePath, tr.Line, tr.ColumnNumber, tr.ContextSnippet
FROM OI_TextReferences tr
JOIN OI_Files f ON f.FileId = tr.FileId
WHERE tr.BuildId = @BuildId AND tr.Token = @FieldName
ORDER BY f.RelativePath, tr.Line, tr.ColumnNumber;

CREATE TABLE #FieldCallerChains
(
    FieldReferenceId UNIQUEIDENTIFIER NOT NULL,
    FunctionId UNIQUEIDENTIFIER NOT NULL,
    Depth INT NOT NULL,
    FunctionPath NVARCHAR(MAX) NOT NULL,
    VisitedIds VARCHAR(MAX) NOT NULL
);

;WITH CallerChain AS
(
    SELECT r.FieldReferenceId, r.ContainingFunctionId AS FunctionId, 0 AS Depth,
           CAST(fn.QualifiedName AS NVARCHAR(MAX)) AS FunctionPath,
           CAST('|' + CONVERT(VARCHAR(36), r.ContainingFunctionId) + '|' AS VARCHAR(MAX)) AS VisitedIds
    FROM OI_FieldReferences r
    JOIN #TargetFields t ON t.SymbolId = r.FieldSymbolId
    JOIN OI_Symbols fn ON fn.SymbolId = r.ContainingFunctionId
    WHERE r.BuildId = @BuildId AND r.ContainingFunctionId IS NOT NULL

    UNION ALL

    SELECT c.FieldReferenceId, fc.CallerFunctionId, c.Depth + 1,
           CAST(caller.QualifiedName + N' -> ' + c.FunctionPath AS NVARCHAR(MAX)),
           CAST(c.VisitedIds + CONVERT(VARCHAR(36), fc.CallerFunctionId) + '|' AS VARCHAR(MAX))
    FROM CallerChain c
    JOIN OI_FunctionCalls fc ON fc.BuildId = @BuildId AND fc.CalledFunctionId = c.FunctionId
    JOIN OI_Symbols caller ON caller.SymbolId = fc.CallerFunctionId
    WHERE c.Depth < 100
      AND CHARINDEX('|' + CONVERT(VARCHAR(36), fc.CallerFunctionId) + '|', c.VisitedIds) = 0
)
INSERT INTO #FieldCallerChains
SELECT FieldReferenceId, FunctionId, Depth, FunctionPath, VisitedIds
FROM CallerChain
OPTION (MAXRECURSION 32767);

SELECT r.AccessKind, directFile.RelativePath AS ReferenceFile, r.Line AS ReferenceLine,
       c.Depth, c.FunctionPath,
       CASE WHEN NOT EXISTS
       (
           SELECT 1 FROM OI_FunctionCalls parent
           WHERE parent.BuildId = @BuildId AND parent.CalledFunctionId = c.FunctionId
       ) THEN 1 ELSE 0 END AS IsRoot
FROM #FieldCallerChains c
JOIN OI_FieldReferences r ON r.FieldReferenceId = c.FieldReferenceId
JOIN OI_Files directFile ON directFile.FileId = r.FileId
ORDER BY directFile.RelativePath, r.Line, c.Depth DESC, c.FunctionPath;

;WITH RelevantFiles AS
(
    SELECT d.FileId, N'FIELD_DECLARATION' AS Reason
    FROM #TargetFields t JOIN OI_Declarations d ON d.SymbolId = t.SymbolId AND d.BuildId = @BuildId
    UNION
    SELECT r.FileId, N'FIELD_REFERENCE'
    FROM #TargetFields t JOIN OI_FieldReferences r ON r.FieldSymbolId = t.SymbolId AND r.BuildId = @BuildId

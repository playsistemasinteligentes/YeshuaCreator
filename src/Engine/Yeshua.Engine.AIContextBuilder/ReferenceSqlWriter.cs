        await writer.WriteLineAsync("COMMIT TRANSACTION;");
    }

    private static async Task WriteRowsAsync<T>(
        StreamWriter writer,
        string table,
        string columns,
        IEnumerable<T> sourceRows,
        Func<T, string> format)
    {
        const int batchSize = 500;
        var rows = sourceRows.ToArray();

        for (var offset = 0; offset < rows.Length; offset += batchSize)
        {
            var batch = rows.Skip(offset).Take(batchSize).Select(format).ToArray();
            await writer.WriteLineAsync();
            await writer.WriteLineAsync($"INSERT INTO {table} ({columns}) VALUES");
            await writer.WriteLineAsync(string.Join(",\n", batch));
            await writer.WriteLineAsync(";");
        }
    }

    private static string SqlString(string? value)
    {
        if (value == null)
            return "NULL";

        var escaped = value
            .Replace("'", "''")
            .Replace("$(", "' + NCHAR(36) + N'(");
        return $"N'{escaped}'";
    }

    private static string SqlGuid(Guid value) => $"'{value:D}'";
    private static string SqlGuid(Guid? value) => value.HasValue ? SqlGuid(value.Value) : "NULL";
    private static string SqlInt(int? value) => value?.ToString() ?? "NULL";
    private static string SqlBool(bool value) => value ? "1" : "0";
    private static string SqlDateTime(DateTimeOffset value) => $"'{value.UtcDateTime:yyyy-MM-ddTHH:mm:ss.fffffffZ}'";


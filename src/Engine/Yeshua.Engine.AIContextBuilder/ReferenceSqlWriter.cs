    public static async Task WriteAsync(ReferenceIndexModel model, string outputDirectory)
    {
        Directory.CreateDirectory(outputDirectory);

        await File.WriteAllTextAsync(
            Path.Combine(outputDirectory, "00-reference-index-schema.sql"),
            Schema,
            new UTF8Encoding(false));

        await WriteDataAsync(
            model,
            Path.Combine(outputDirectory, "01-reference-index-data.sql"));

        await File.WriteAllTextAsync(
            Path.Combine(outputDirectory, "02-query-field-sources.sql"),
            RenderQuery(FieldQuerySql, model, GetExampleSymbol(model, "PROPERTY", "FIELD")),
            new UTF8Encoding(false));

        await File.WriteAllTextAsync(
            Path.Combine(outputDirectory, "03-query-class-sources.sql"),
            RenderQuery(ClassQuerySql, model, GetExampleSymbol(model, "CLASS")),
            new UTF8Encoding(false));

        await File.WriteAllTextAsync(
            Path.Combine(outputDirectory, "04-query-function-sources.sql"),
            RenderQuery(
                FunctionQuerySql,
                model,
                GetExampleSymbol(model, "METHOD", "CONSTRUCTOR", "ACCESSOR", "LOCAL_FUNCTION", "LAMBDA")),
            new UTF8Encoding(false));
    }

    internal static string Schema => SchemaSql + Environment.NewLine + ExtensionSchemaSql;

    private static string RenderQuery(string template, ReferenceIndexModel model, string exampleSymbol)
    {
        return template
            .Replace("__APPLICATION__", SqlString(model.ApplicationName), StringComparison.Ordinal)
            .Replace("__VERSION__", SqlString(model.Version), StringComparison.Ordinal)
            .Replace("__SYMBOL__", SqlString(exampleSymbol), StringComparison.Ordinal);
    }

    private static string GetExampleSymbol(ReferenceIndexModel model, params string[] kinds)
    {
        var kindPriority = kinds
            .Select((kind, index) => new { kind, index })
            .ToDictionary(item => item.kind, item => item.index, StringComparer.Ordinal);
        var seedProjectIds = model.Projects.Values
            .Where(project => project.IsSeedProject)
            .Select(project => project.ProjectId)
            .ToHashSet();

        return model.Symbols.Values
                   .Where(symbol => kindPriority.ContainsKey(symbol.Kind))
                   .Where(symbol => !symbol.Name.StartsWith('<') &&
                                    !symbol.QualifiedName.StartsWith('<') &&
                                    !symbol.QualifiedName.StartsWith('('))
                   .OrderByDescending(symbol => seedProjectIds.Contains(symbol.ProjectId))
                   .ThenByDescending(symbol => symbol.QualifiedName.Contains(".Entitys.", StringComparison.Ordinal))
                   .ThenBy(symbol => kindPriority[symbol.Kind])
                   .ThenBy(symbol => symbol.QualifiedName, StringComparer.Ordinal)
                   .Select(symbol => symbol.QualifiedName)
                   .FirstOrDefault()
               ?? "REPLACE_WITH_SYMBOL";
    }


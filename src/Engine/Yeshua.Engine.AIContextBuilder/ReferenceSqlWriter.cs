    private const string ClassQuerySql = """
-- Adjust only these values.
DECLARE @ApplicationName NVARCHAR(300) = __APPLICATION__;
DECLARE @Version NVARCHAR(200) = __VERSION__;
DECLARE @ClassQualifiedName NVARCHAR(2000) = __SYMBOL__;

DECLARE @BuildId UNIQUEIDENTIFIER;
SELECT TOP (1) @BuildId = b.BuildId
FROM OI_Builds b
JOIN OI_Applications a ON a.ApplicationId = b.ApplicationId
WHERE a.Name = @ApplicationName AND b.Version = @Version
ORDER BY b.GeneratedAtUtc DESC;

IF @BuildId IS NULL THROW 51000, 'Build not found.', 1;

DECLARE @ClassName NVARCHAR(500) = RIGHT(@ClassQualifiedName, CHARINDEX('.', REVERSE(@ClassQualifiedName) + '.') - 1);
CREATE TABLE #TargetClasses (SymbolId UNIQUEIDENTIFIER NOT NULL PRIMARY KEY);
INSERT INTO #TargetClasses
SELECT SymbolId FROM OI_Symbols
WHERE BuildId = @BuildId
  AND Kind = N'CLASS'
  AND (QualifiedName = @ClassQualifiedName OR Name = @ClassName);

SELECT s.QualifiedName, f.RelativePath, d.StartLine, d.EndLine
FROM #TargetClasses t
JOIN OI_Symbols s ON s.SymbolId = t.SymbolId
JOIN OI_Declarations d ON d.BuildId = @BuildId AND d.SymbolId = t.SymbolId
JOIN OI_Files f ON f.FileId = d.FileId
ORDER BY f.RelativePath, d.StartLine;

SELECT s.QualifiedName, f.RelativePath, i.Line, i.ColumnNumber,
       owner.QualifiedName AS ContainingFunction
FROM #TargetClasses t
JOIN OI_Symbols s ON s.SymbolId = t.SymbolId
JOIN OI_ClassInstantiations i ON i.BuildId = @BuildId AND i.ClassSymbolId = t.SymbolId
JOIN OI_Files f ON f.FileId = i.FileId
LEFT JOIN OI_Symbols owner ON owner.SymbolId = i.ContainingFunctionId
ORDER BY f.RelativePath, i.Line;

SELECT tr.Token, tr.ReferenceKind, f.RelativePath, tr.Line, tr.ColumnNumber, tr.ContextSnippet
FROM OI_TextReferences tr
JOIN OI_Files f ON f.FileId = tr.FileId
WHERE tr.BuildId = @BuildId AND tr.Token = @ClassName
ORDER BY f.RelativePath, tr.Line, tr.ColumnNumber;

CREATE TABLE #ClassCallerChains
(
    InstantiationId UNIQUEIDENTIFIER NOT NULL,
    FunctionId UNIQUEIDENTIFIER NOT NULL,
    Depth INT NOT NULL,
    FunctionPath NVARCHAR(MAX) NOT NULL,
    VisitedIds VARCHAR(MAX) NOT NULL
);

;WITH CallerChain AS
(
    SELECT i.InstantiationId, i.ContainingFunctionId AS FunctionId, 0 AS Depth,
           CAST(fn.QualifiedName AS NVARCHAR(MAX)) AS FunctionPath,
           CAST('|' + CONVERT(VARCHAR(36), i.ContainingFunctionId) + '|' AS VARCHAR(MAX)) AS VisitedIds
    FROM OI_ClassInstantiations i
    JOIN #TargetClasses t ON t.SymbolId = i.ClassSymbolId
    JOIN OI_Symbols fn ON fn.SymbolId = i.ContainingFunctionId
    WHERE i.BuildId = @BuildId AND i.ContainingFunctionId IS NOT NULL

    UNION ALL

    SELECT c.InstantiationId, fc.CallerFunctionId, c.Depth + 1,
           CAST(caller.QualifiedName + N' -> ' + c.FunctionPath AS NVARCHAR(MAX)),
           CAST(c.VisitedIds + CONVERT(VARCHAR(36), fc.CallerFunctionId) + '|' AS VARCHAR(MAX))
    FROM CallerChain c
    JOIN OI_FunctionCalls fc ON fc.BuildId = @BuildId AND fc.CalledFunctionId = c.FunctionId
    JOIN OI_Symbols caller ON caller.SymbolId = fc.CallerFunctionId
    WHERE c.Depth < 100
      AND CHARINDEX('|' + CONVERT(VARCHAR(36), fc.CallerFunctionId) + '|', c.VisitedIds) = 0
)
INSERT INTO #ClassCallerChains
SELECT InstantiationId, FunctionId, Depth, FunctionPath, VisitedIds
FROM CallerChain
OPTION (MAXRECURSION 32767);

SELECT sourceFile.RelativePath AS InstantiationFile, i.Line AS InstantiationLine,
       c.Depth, c.FunctionPath,
       CASE WHEN NOT EXISTS
       (
           SELECT 1 FROM OI_FunctionCalls parent
           WHERE parent.BuildId = @BuildId AND parent.CalledFunctionId = c.FunctionId
       ) THEN 1 ELSE 0 END AS IsRoot
FROM #ClassCallerChains c
JOIN OI_ClassInstantiations i ON i.InstantiationId = c.InstantiationId
JOIN OI_Files sourceFile ON sourceFile.FileId = i.FileId
ORDER BY sourceFile.RelativePath, i.Line, c.Depth DESC, c.FunctionPath;

;WITH RelevantFiles AS
(
    SELECT d.FileId, N'CLASS_DECLARATION' AS Reason
    FROM #TargetClasses t JOIN OI_Declarations d ON d.SymbolId = t.SymbolId AND d.BuildId = @BuildId
    UNION
    SELECT i.FileId, N'CLASS_INSTANTIATION'
    FROM #TargetClasses t JOIN OI_ClassInstantiations i ON i.ClassSymbolId = t.SymbolId AND i.BuildId = @BuildId
    UNION
    SELECT d.FileId, N'CALLER_CHAIN'
    FROM #ClassCallerChains c JOIN OI_Declarations d ON d.SymbolId = c.FunctionId AND d.BuildId = @BuildId
    UNION
    SELECT tr.FileId, N'TEXT_REFERENCE'
    FROM OI_TextReferences tr
    WHERE tr.BuildId = @BuildId AND tr.Token = @ClassName
)
SELECT DISTINCT f.RelativePath, rf.Reason
FROM RelevantFiles rf JOIN OI_Files f ON f.FileId = rf.FileId
ORDER BY f.RelativePath, rf.Reason;
""";

    private const string FunctionQuerySql = """
-- Use the function reported by the log. Line is optional but helps disambiguate overloads and lambdas.
DECLARE @ApplicationName NVARCHAR(300) = __APPLICATION__;
DECLARE @Version NVARCHAR(200) = __VERSION__;
DECLARE @FunctionSearch NVARCHAR(2000) = __SYMBOL__;
DECLARE @FilePath NVARCHAR(2000) = NULL;
DECLARE @Line INT = NULL;

DECLARE @BuildId UNIQUEIDENTIFIER;
SELECT TOP (1) @BuildId = b.BuildId
FROM OI_Builds b
JOIN OI_Applications a ON a.ApplicationId = b.ApplicationId
WHERE a.Name = @ApplicationName AND b.Version = @Version
ORDER BY b.GeneratedAtUtc DESC;

IF @BuildId IS NULL THROW 51000, 'Build not found.', 1;

DECLARE @FunctionName NVARCHAR(500) = RIGHT(@FunctionSearch, CHARINDEX('.', REVERSE(@FunctionSearch) + '.') - 1);
CREATE TABLE #TargetFunctions (FunctionId UNIQUEIDENTIFIER NOT NULL PRIMARY KEY);
INSERT INTO #TargetFunctions
SELECT DISTINCT s.SymbolId
FROM OI_Symbols s
LEFT JOIN OI_Declarations d ON d.BuildId = @BuildId AND d.SymbolId = s.SymbolId
LEFT JOIN OI_Files f ON f.FileId = d.FileId
WHERE s.BuildId = @BuildId
  AND s.Kind IN (N'METHOD', N'CONSTRUCTOR', N'ACCESSOR', N'LOCAL_FUNCTION', N'LAMBDA')
  AND (s.QualifiedName = @FunctionSearch OR s.Name = @FunctionName)
  AND (@FilePath IS NULL OR REPLACE(f.RelativePath, '\', '/') LIKE N'%' + REPLACE(@FilePath, '\', '/') + N'%')
  AND (@Line IS NULL OR @Line BETWEEN d.StartLine AND d.EndLine);

CREATE TABLE #FunctionClosure
(
    DirectionName NVARCHAR(20) NOT NULL,
    FunctionId UNIQUEIDENTIFIER NOT NULL,
    Depth INT NOT NULL,
    FunctionPath NVARCHAR(MAX) NOT NULL,
    VisitedIds VARCHAR(MAX) NOT NULL
);

;WITH Upstream AS
(
    SELECT t.FunctionId, 0 AS Depth, CAST(s.QualifiedName AS NVARCHAR(MAX)) AS FunctionPath,
           CAST('|' + CONVERT(VARCHAR(36), t.FunctionId) + '|' AS VARCHAR(MAX)) AS VisitedIds
    FROM #TargetFunctions t JOIN OI_Symbols s ON s.SymbolId = t.FunctionId
    UNION ALL
    SELECT fc.CallerFunctionId, u.Depth + 1,
           CAST(caller.QualifiedName + N' -> ' + u.FunctionPath AS NVARCHAR(MAX)),
           CAST(u.VisitedIds + CONVERT(VARCHAR(36), fc.CallerFunctionId) + '|' AS VARCHAR(MAX))
    FROM Upstream u
    JOIN OI_FunctionCalls fc ON fc.BuildId = @BuildId AND fc.CalledFunctionId = u.FunctionId
    JOIN OI_Symbols caller ON caller.SymbolId = fc.CallerFunctionId
    WHERE u.Depth < 100
      AND CHARINDEX('|' + CONVERT(VARCHAR(36), fc.CallerFunctionId) + '|', u.VisitedIds) = 0
)
INSERT INTO #FunctionClosure
SELECT N'UPSTREAM', FunctionId, Depth, FunctionPath, VisitedIds FROM Upstream
OPTION (MAXRECURSION 32767);

;WITH Downstream AS
(
    SELECT t.FunctionId, 0 AS Depth, CAST(s.QualifiedName AS NVARCHAR(MAX)) AS FunctionPath,
           CAST('|' + CONVERT(VARCHAR(36), t.FunctionId) + '|' AS VARCHAR(MAX)) AS VisitedIds
    FROM #TargetFunctions t JOIN OI_Symbols s ON s.SymbolId = t.FunctionId
    UNION ALL
    SELECT fc.CalledFunctionId, d.Depth + 1,
           CAST(d.FunctionPath + N' -> ' + called.QualifiedName AS NVARCHAR(MAX)),
           CAST(d.VisitedIds + CONVERT(VARCHAR(36), fc.CalledFunctionId) + '|' AS VARCHAR(MAX))
    FROM Downstream d
    JOIN OI_FunctionCalls fc ON fc.BuildId = @BuildId AND fc.CallerFunctionId = d.FunctionId
    JOIN OI_Symbols called ON called.SymbolId = fc.CalledFunctionId
    WHERE d.Depth < 100
      AND CHARINDEX('|' + CONVERT(VARCHAR(36), fc.CalledFunctionId) + '|', d.VisitedIds) = 0
)
INSERT INTO #FunctionClosure
SELECT N'DOWNSTREAM', FunctionId, Depth, FunctionPath, VisitedIds FROM Downstream
OPTION (MAXRECURSION 32767);

SELECT DirectionName, Depth, FunctionPath
FROM #FunctionClosure
ORDER BY DirectionName, Depth, FunctionPath;

SELECT DISTINCT f.RelativePath AS RelativePath, c.DirectionName AS DirectionName
FROM #FunctionClosure c
JOIN OI_Declarations d ON d.BuildId = @BuildId AND d.SymbolId = c.FunctionId
JOIN OI_Files f ON f.FileId = d.FileId
UNION
SELECT DISTINCT f.RelativePath, N'TEXT_REFERENCE'
FROM OI_TextReferences tr
JOIN OI_Files f ON f.FileId = tr.FileId
WHERE tr.BuildId = @BuildId AND tr.Token = @FunctionName
ORDER BY RelativePath, DirectionName;
""";
